// Prints a markdown frame-data table for every character JSON in src/characters.
// Usage: node scripts/framedata.mjs [characterId]   (writes docs/frame-data-<id>.md)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/characters/', import.meta.url);
const only = process.argv[2];
const files = readdirSync(dir).filter((f) => f.endsWith('.moves.json') && (!only || f.startsWith(only + '.')));
const ORDER = ['jab', 'smash', 'aerial', 'grab', 'throw', 'special', 'ultimate'];

for (const file of files) {
  const id = file.replace('.moves.json', '');
  const json = JSON.parse(readFileSync(new URL(file, dir), 'utf8'));
  const moves = Object.entries(json.moves).sort((a, b) => ORDER.indexOf(a[1].kind) - ORDER.indexOf(b[1].kind));
  const rows = [];
  for (const [mid, m] of moves) {
    const notes = [];
    if (m.charge) notes.push(`charge x${m.charge.damageMult} dmg`);
    if (m.armor) notes.push(`armor f${m.armor.from}-${m.armor.to}${m.armor.threshold === 0 ? ' (needs bonus)' : m.armor.threshold ? ` (<=${m.armor.threshold} dmg)` : ' (super)'}`);
    if (m.landingLag) notes.push(`landing lag ${m.landingLag}`);
    if (m.requires) notes.push(`needs ${m.requires.key} >= ${m.requires.min}`);
    if (m.helpless) notes.push('helpless after');
    if (m.noLedge) notes.push(`no ledge grab f1-${m.noLedge}`);
    if (m.next) notes.push(`chains to ${m.next.id}`);
    if (m.hidden) notes.push('internal');
    if (m.cinematic) notes.push(`cinematic ${m.cinematic.frames}f`);
    const total = m.startup + m.active + m.recovery;
    if (!m.hitboxes.length) {
      rows.push(`| ${m.name} (\`${mid}\`) | ${m.kind} | ${m.startup} | ${m.active} | ${m.recovery} | ${total} | - | - | - | - | ${notes.join('; ')} |`);
      continue;
    }
    m.hitboxes.forEach((h, i) => {
      const extra = [...(i === 0 ? notes : []), h.grab ? 'grab' : '', h.throw ? 'throw' : '', h.breaksShield ? 'breaks shield' : '', h.minCharge ? `needs ${h.minCharge * 100}% charge` : '', h.unblockable ? 'unblockable' : ''].filter(Boolean).join('; ');
      rows.push(`| ${i === 0 ? `${m.name} (\`${mid}\`)` : '&nbsp;&nbsp;↳ hitbox ' + (i + 1)} | ${i === 0 ? m.kind : ''} | ${i === 0 ? m.startup : ''} | ${i === 0 ? m.active : ''} | ${i === 0 ? m.recovery : ''} | ${i === 0 ? total : ''} | ${h.damage} | ${h.angle} | ${h.base} | ${h.scaling} | ${extra} |`);
    });
  }
  const md = [
    `# ${id}: frame data`,
    '',
    '_Generated by `node scripts/framedata.mjs`. Frames are 1/60 s; frame 1 is the frame the move starts on. Angle: 0 ahead, 90 up, 180 behind, 270 spike, 361 auto. BKB = base knockback, KBG = knockback growth (scaling)._',
    '',
    '| Move | Kind | Startup | Active | Recovery | Total | Dmg | Angle | BKB | KBG | Notes |',
    '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---|',
    ...rows,
    '',
  ].join('\n');
  writeFileSync(new URL(`../docs/frame-data-${id}.md`, import.meta.url), md);
  console.log(`wrote docs/frame-data-${id}.md (${moves.length} moves)`);
}
