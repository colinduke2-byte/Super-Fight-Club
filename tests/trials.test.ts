import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { CHARACTERS } from '../src/characters';
import { Fighter } from '../src/engine/fighter';
import { World } from '../src/engine/world';
import { TrialRun, type TrialPlan } from '../src/game/trialDemo';
import { TRIAL_PLANS } from '../src/game/trialPlans';
import { MECHANIC_TRIALS, TRIALS, TrialChecker, trialsFor } from '../src/game/trials';
import { STAGES } from '../src/stages';
import { solveTrial } from './tools/trialSolver';

const UPDATE = !!process.env.UPDATE_TRIAL_PLANS;
const found: Record<string, TrialPlan> = {};

describe('combo trials are true combos', () => {
  it('a string whose hits do not link (the dummy recovers in between) does not clear', () => {
    const world = new World(STAGES.classic);
    const p = new Fighter(0, CHARACTERS.brick);
    const d = new Fighter(1, CHARACTERS.nova);
    world.addFighter(p);
    world.addFighter(d);
    const c = new TrialChecker({ id: 't', name: 't', steps: ['jab1', 'jab1'], percent: 0, tip: '' }, p, d);
    c.onHit('jab1', 1);
    c.onHit('jab1', 1); // second hit lands as a fresh combo (the dummy was out of hitstun)
    expect(c.done).toBe(false);
    c.onHit('jab1', 2);
    expect(c.done).toBe(true);
  });

  it('a step with a condition only counts when it holds (a soaked dummy)', () => {
    const world = new World(STAGES.classic);
    const p = new Fighter(0, CHARACTERS.riptide);
    const d = new Fighter(1, CHARACTERS.nova);
    world.addFighter(p);
    world.addFighter(d);
    const c = new TrialChecker(MECHANIC_TRIALS.riptide, p, d);
    c.onHit('utilt', 1);
    c.onHit('uair', 2); // not soaked: does not count
    expect(c.done).toBe(false);
    c.onHit('utilt', 1);
    d.status.soak = 60;
    c.onHit('uair', 2);
    expect(c.done).toBe(true);
  });

  it('every fighter has a trial of its own mechanic', () => {
    for (const id of Object.keys(TRIALS)) expect(MECHANIC_TRIALS[id], id).toBeDefined();
  });

  // every trial of every fighter is cleared in the sim, judged by the real TrialChecker: by its stored plan (the one the DEMO
  // plays) or, when that is missing or no longer clears, by a fresh solver search
  for (const id of Object.keys(TRIALS)) {
    it(`${id}: all ${trialsFor(id).length} trials can be completed (and their demo plan clears them)`, () => {
      for (const t of trialsFor(id)) {
        const key = `${id}:${t.id}`;
        const stored = TRIAL_PLANS[key];
        const ok = !!stored && new TrialRun(id, t, stored).run();
        if (ok && !UPDATE) {
          found[key] = stored;
          continue;
        }
        const plan = solveTrial(id, t);
        expect(plan, `${id} ${t.name} (${t.steps.join(' > ')} at ${t.percent}%)`).not.toBeNull();
        if (plan) found[key] = plan;
        if (!UPDATE) expect(ok, `${key}: stored demo plan missing or stale (run with UPDATE_TRIAL_PLANS=1)`).toBe(true);
      }
    }, 240_000);
  }

  it.runIf(UPDATE)('writes the proved plans', () => {
    const body = Object.entries(found)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([k, p]) => `  '${k}': { gap: ${p.gap}, segs: [${p.segs.map((s) => JSON.stringify(s).replace(/"(\w+)":/g, '$1: ').replace(/"/g, "'").replace(/,/g, ', ')).join(', ')}] },`)
      .join('\n');
    const src = `import type { TrialPlan } from './trialDemo';

/**
 * Proved plans for every combo trial, '<fighter>:<trial id>' -> plan: what the Training menu's DEMO plays. Generated by the
 * trial solver (UPDATE_TRIAL_PLANS=1 npx vitest run tests/trials.test.ts); tests/trials.test.ts checks each still clears.
 */
export const TRIAL_PLANS: Record<string, TrialPlan> = {
${body}
};
`;
    writeFileSync(new URL('../src/game/trialPlans.ts', import.meta.url), src);
  });
});
