import { writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { CpuController } from '../src/ai/cpu';
import { CHARACTER_AI, type CpuLevel } from '../src/ai/profiles';
import { CHARACTERS } from '../src/characters';
import { makeInput } from '../src/engine/buttons';
import { Fighter } from '../src/engine/fighter';
import { Match } from '../src/engine/match';
import { World } from '../src/engine/world';
import { STAGES } from '../src/stages';

/**
 * Round-robin CPU-vs-CPU report: `BALANCE=1 npx vitest run tests/balanceReport.test.ts` writes docs/balance-report.md.
 * It measures the roster as the CPU plays it (so it under-rates styles the AI plays badly); use it to spot outliers after
 * changing frame data, not as proof of human balance.
 */
function duel(a: string, b: string, stage: string, level: CpuLevel, seed: number): { winner: number; ult: number[]; ticks: number } {
  const world = new World(STAGES[stage]);
  const fs = [a, b].map((c, i) => new Fighter(i, CHARACTERS[c]));
  fs.forEach((f) => world.addFighter(f));
  const match = new Match(world, { mode: 'stock', stocks: 3, timeLimitSec: 0, respawnDelay: 70 });
  const sp = STAGES[stage].spawns;
  const place = (f: Fighter, air = false): void => f.spawn(sp[f.id].x, sp[f.id].y - (air ? 130 : 1), sp[f.id].x <= 0 ? 1 : -1);
  fs.forEach((f) => place(f));
  match.onRespawn = (f) => place(f, true);
  const ult = [0, 0];
  world.listener = (type, f, _x, _y, _m, extra) => {
    if (type === 'ko') match.onKo(f, extra);
    if (type === 'moveStart' && f.move?.id.startsWith('ultimate')) ult[f.id]++;
  };
  const cpus = [new CpuController(level, seed * 2 + 1), new CpuController(level, seed * 2 + 2)];
  const ins = fs.map(() => makeInput());
  let t = 0;
  for (; t < 14400 && !match.over; t++) {
    fs.forEach((f, i) => cpus[i].update(f, world, ins[i]));
    world.step(ins);
    match.step();
  }
  return { winner: match.over ? match.winner : -1, ult, ticks: t };
}

/** Dev tuning: BALANCE_PATCH='{"vex.stats.weight":90,"brick.moves.usmash.armor.threshold":8}' sets values at runtime; a key ending in * multiplies; '#' walks an array, '*' every value of an object (e.g. nova.moves.*.hitboxes.#.damage*). */
function applyPatch(): void {
  const raw = process.env.BALANCE_PATCH;
  if (!raw) return;
  for (const [key, val] of Object.entries(JSON.parse(raw) as Record<string, number | string>)) {
    const mul = key.endsWith('*');
    const path = (mul ? key.slice(0, -1) : key).split('.');
    const expand = (obj: any, rest: string[]): void => {
      const [head, ...tail] = rest;
      if (head === '#') {
        for (const item of Array.isArray(obj) ? obj : []) expand(item, tail);
        return;
      }
      if (head === '*') {
        for (const item of Object.values(obj ?? {})) expand(item, tail);
        return;
      }
      if (tail.length === 0) obj[head] = mul ? obj[head] * (val as number) : val;
      else expand(obj[head], tail);
    };
    if (path[0] === 'ai') expand(CHARACTER_AI, path.slice(1));
    else expand(CHARACTERS, path);
  }
}

const SEEDS = Number(process.env.BALANCE_SEEDS ?? 4);

describe.skipIf(!process.env.BALANCE)('balance report', () => {
  it('round robin', () => {
    applyPatch();
    const ids = Object.keys(CHARACTERS);
    let md = `# CPU-vs-CPU balance report\n\nGenerated by \`BALANCE=1 npx vitest run tests/balanceReport.test.ts\`. Each pairing: 3 stages x ${SEEDS} seeds x both sides = ${SEEDS * 6} matches (3 stocks).\nThe CPU plays some characters better than others, so read this as a smoke test for outliers, not as human balance.\n\n`;
    const only = process.env.BALANCE_LEVELS; // e.g. BALANCE_LEVELS=3 for a quick run (writes to $BALANCE_OUT instead of docs/)
    for (const level of (only ? [Number(only)] : [3, 2]) as CpuLevel[]) {
      const wins: Record<string, number> = {};
      const games: Record<string, number> = {};
      const ults: Record<string, number> = {};
      const secs: number[] = [];
      let table = '| pairing | wins |\n|---|---|\n';
      for (let i = 0; i < ids.length; i++) {
        for (let j = i + 1; j < ids.length; j++) {
          const focus = process.env.BALANCE_ONLY ? process.env.BALANCE_ONLY.split(',') : undefined; // e.g. BALANCE_ONLY=nova: only that fighter's pairings
          if (focus && !focus.includes(ids[i]) && !focus.includes(ids[j])) continue;
          let wa = 0;
          let wb = 0;
          for (const stage of ['classic', 'ring', 'reactor']) {
            for (let seed = 0; seed < SEEDS; seed++) {
              for (const flip of [false, true]) {
                const [x, y] = flip ? [ids[j], ids[i]] : [ids[i], ids[j]];
                const r = duel(x, y, stage, level, seed);
                secs.push(r.ticks / 60);
                ults[x] = (ults[x] ?? 0) + r.ult[0];
                ults[y] = (ults[y] ?? 0) + r.ult[1];
                if (r.winner < 0) continue;
                if ((r.winner === 0 ? x : y) === ids[i]) wa++;
                else wb++;
              }
            }
          }
          table += `| ${ids[i]} vs ${ids[j]} | ${wa} - ${wb} |\n`;
          wins[ids[i]] = (wins[ids[i]] ?? 0) + wa;
          wins[ids[j]] = (wins[ids[j]] ?? 0) + wb;
          games[ids[i]] = (games[ids[i]] ?? 0) + wa + wb;
          games[ids[j]] = (games[ids[j]] ?? 0) + wa + wb;
        }
      }
      md += `## Level ${level}\n\n${table}\n| fighter | win rate | ultimates used per match |\n|---|---|---|\n`;
      for (const c of ids) md += `| ${c} | ${((100 * wins[c]) / games[c]).toFixed(0)}% | ${(ults[c] / (games[c] / 1)).toFixed(2)} |\n`;
      md += `\nMean match length: ${(secs.reduce((p, c) => p + c, 0) / secs.length).toFixed(0)} s\n\n`;
    }
    writeFileSync(process.env.BALANCE_OUT ?? 'docs/balance-report.md', md);
  }, 1_800_000);
});
